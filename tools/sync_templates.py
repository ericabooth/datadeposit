#!/usr/bin/env python3
"""Keep the three copies of the setup-script templates identical.

spec/templates/ holds the master copies. This script:
  * copies them to r/inst/templates/ and python/src/datadeposit/templates/;
  * embeds them in stata/src/datadeposit.ado as a Mata function, encoding every
    character that Stata could treat as a macro, comment, or continuation
    marker with char(), so the ado-file stays a single installable file;
  * writes the version in VERSION into DESCRIPTION, pyproject.toml, the ado
    header, the .pkg, and the package-version strings.

Usage:  python3 tools/sync_templates.py          # rewrite the copies
        python3 tools/sync_templates.py --check  # exit 1 if anything is out of sync
"""
import pathlib
import re
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SPEC = ROOT / "spec" / "templates"
LANGS = {"do": "setup.do", "R": "setup.R", "py": "setup.py"}
ADO = ROOT / "stata" / "src" / "datadeposit.ado"
BEGIN = "* ===== BEGIN EMBEDDED TEMPLATES (generated by tools/sync_templates.py; do not edit) ====="
END = "* ===== END EMBEDDED TEMPLATES ====="
RISKY = set('`$"\\/*') | {"\t", "\r"}


def embedded_block():
    """Each template becomes hex text in a few long literals; Mata decodes it.

    Hex has no character Stata could expand or treat as a comment, and a
    handful of 2,000-character literals stays far below Mata's per-function
    limit on string literals.
    """
    out = [BEGIN, "version 14", "mata:", "string scalar _ddp_template(string scalar which)", "{",
           "    string scalar h", '    h = ""']
    for key, fname in LANGS.items():
        hx = (SPEC / fname).read_bytes().hex()
        out.append('    if (which == "%s") {' % key)
        for k in range(0, len(hx), 2000):
            out.append('        h = h + "%s"' % hx[k:k + 2000])
        out.append("    }")
    out += ["    return(_ddp_unhex(h))", "}", "",
            "string scalar _ddp_unhex(string scalar h)",
            "{",
            "    real rowvector b, idx",
            "    if (h == \"\") return(\"\")",
            "    b = ascii(h)",
            "    b = b :- 48 :- 39 :* (b :>= 97)",
            "    idx = (1..(cols(b) / 2)) :* 2",
            "    return(char(16 :* b[idx :- 1] :+ b[idx]))",
            "}",
            "end", END]
    return "\n".join(out) + "\n"


def version():
    return (ROOT / "VERSION").read_text().strip()


def targets():
    v = version()
    ado = ADO.read_text(encoding="utf-8")
    i, j = ado.index(BEGIN), ado.index(END) + len(END) + 1
    ado = ado[:i] + embedded_block() + ado[j:]
    ado = re.sub(r"^\*! version \S+", "*! version " + v, ado, count=1, flags=re.M)
    ado = re.sub(r'"datadeposit \d+\.\d+\.\d+"', '"datadeposit %s"' % v, ado)
    files = {ADO: ado}
    for key, fname in LANGS.items():
        src = (SPEC / fname).read_bytes()
        files[ROOT / "r" / "inst" / "templates" / fname] = src
        files[ROOT / "python" / "src" / "datadeposit" / "templates" / fname] = src
    rt = (SPEC / "setup.R").read_text(encoding="utf-8")
    blk = rt[rt.index("# >>> exact-double"):rt.index("  # <<< exact-double")]
    blk = blk[blk.index("\n") + 1:]
    files[ROOT / "r" / "R" / "exact.R"] = (
        "# Generated by tools/sync_templates.py from spec/templates/setup.R; do not edit.\n"
        "# Base R's parser is not correctly rounded for 17-digit text; this is the same\n"
        "# repair the deposit's setup.R applies.\n"
        "dd_exact_double <- local({\n" + blk + "  exact_double\n})\n")
    for fx in ("survey_edge.dta", "auto.dta"):
        files[ROOT / "r" / "tests" / "testthat" / "fixtures" / fx] = (ROOT / "tests" / "fixtures" / fx).read_bytes()
    desc = ROOT / "r" / "DESCRIPTION"
    if desc.exists():
        files[desc] = re.sub(r"^Version: .*$", "Version: " + v, desc.read_text(), flags=re.M)
    pyp = ROOT / "python" / "pyproject.toml"
    if pyp.exists():
        files[pyp] = re.sub(r'^version = ".*"$', 'version = "%s"' % v, pyp.read_text(), flags=re.M)
    for p in [ROOT / "python" / "src" / "datadeposit" / "__init__.py", ROOT / "r" / "R" / "util.R"]:
        if p.exists():
            files[p] = re.sub(r'(PACKAGE_VERSION\s*(?:=|<-)\s*")[^"]*(")', r"\g<1>%s\g<2>" % v, p.read_text())
    pkg = ROOT / "stata" / "datadeposit.pkg"
    if pkg.exists():
        files[pkg] = re.sub(r"^d Version: .*$", "d Version: " + v, pkg.read_text(), flags=re.M)
    return files


def main():
    check = "--check" in sys.argv
    stale = []
    for path, content in targets().items():
        data = content.encode("utf-8") if isinstance(content, str) else content
        if not path.exists() or path.read_bytes() != data:
            stale.append(path.relative_to(ROOT))
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
    if check:
        if stale:
            print("out of sync:", *stale, sep="\n  ")
            sys.exit(1)
        print("all copies in sync (version %s)" % version())
    else:
        print("updated:", *(stale or ["nothing"]), sep="\n  ")


if __name__ == "__main__":
    main()
